// Copies the pure scoring engine from the backend into the app (src/engine/scoring), so the
// phone can show a point the moment it is tapped with exactly the server's rules.
// Run after changing backend/src/engine/scoring: `npm run sync-engine` (a test fails if out of date).
import { mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const from = join(root, '..', 'backend', 'src', 'engine', 'scoring');
const to = join(root, 'src', 'engine', 'scoring');
const HEADER = '// GENERATED by scripts/sync-engine.mjs from backend/src/engine/scoring. Do not edit.\n';

/** Backend imports use ".js" (NodeNext); Metro resolves the plain path. */
export const transform = (source) => HEADER + source.replace(/(from\s+'\.{1,2}\/[^']+)\.js'/g, "$1'");

function files(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return name === 'parked' ? [] : files(path);
    return name.endsWith('.ts') && !name.endsWith('.test.ts') && name !== 'test-helpers.ts' ? [path] : [];
  });
}

export function expected() {
  return Object.fromEntries(files(from).map((path) => [relative(from, path), transform(readFileSync(path, 'utf8'))]));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  rmSync(to, { recursive: true, force: true });
  for (const [path, source] of Object.entries(expected())) {
    mkdirSync(dirname(join(to, path)), { recursive: true });
    writeFileSync(join(to, path), source);
  }
  console.log(`Synced ${Object.keys(expected()).length} engine files into src/engine/scoring`);
}
